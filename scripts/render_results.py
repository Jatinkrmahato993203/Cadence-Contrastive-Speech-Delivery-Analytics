"""
scripts/render_results.py
-------------------------
Write the evaluation numbers from dataset/labels/heldout_results.json into
README.md and technical_report.md (between <!-- RESULTS:BEGIN --> and
<!-- RESULTS:END --> markers), so the documentation can never drift from the
measured results.

Usage:
    python scripts/render_results.py
"""

from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).parent.parent
RESULTS = ROOT / "dataset" / "labels" / "heldout_results.json"
CALIB = ROOT / "dataset" / "labels" / "calibration_report.json"

FLAWS = ("pacing", "pitch", "pause", "volume", "clarity", "combined")
TIERS = (("near_perfect", "mild"), ("moderate", "moderate"), ("egregious", "egregious"))


def _summary_table(r: dict) -> str:
    rows = [("Real orators — JFK, Reagan, Eisenhower — held out (reference = same recording)", "heldout_orators"),
            ("TTS held-out texts 6 & 8 (reference = same recording)", "heldout_tts"),
            ("Human LibriVox readers, same-speaker reference", "real_same_speaker"),
            ("Human readers vs the TTS baseline (different voice)", "real_cross_speaker"),
            ("Mode B — no reference recording, all held-out audio", "mode_b")]
    out = ["| Evaluation set | Clips | Mean target IoU | Mean false-positive seconds / clip |",
           "|---|---|---|---|"]
    for name, key in rows:
        if key in r:
            s = r[key]["summary"]
            out.append(f"| {name} | {s['n_clips']} | {s['mean_target_iou']:.2f} | {s['mean_fp_seconds']:.1f} |")
    return "\n".join(out)


def _tier_table(r: dict, key: str) -> str:
    by = r[key]["summary"]["by_flaw_tier"]
    out = ["| Flaw | mild | moderate | egregious |", "|---|---|---|---|"]
    for f in FLAWS:
        cells = []
        for tier, _ in TIERS:
            v = by.get(f"{f}/{tier}")
            cells.append(f"{v['mean_iou']:.2f} ({v['mean_fp_s']:.0f} s)" if v else "—")
        out.append(f"| {f} | " + " | ".join(cells) + " |")
    return "\n".join(out)


def _clean_pairs(r: dict) -> str:
    if "real_cross_speaker" not in r:
        return ""
    lines = []
    for c in r["real_cross_speaker"]["clean_pairs"]:
        lines.append(f"`{c['clip_id']}` scores {c['score']:.1f}/100 with {c['flagged_seconds']:.1f} s of "
                     f"{c['duration_s']:.0f} s flagged")
    return ("Clean human readings compared with the TTS baseline (both used to set k, so in-sample): "
            + "; ".join(lines) + ".")


def render() -> tuple[str, str]:
    r = json.loads(RESULTS.read_text())
    import yaml
    cal = json.loads(CALIB.read_text()) if CALIB.exists() else {}
    g = yaml.safe_load((ROOT / "config.yaml").read_text())["grounding"]
    grad = r.get("severity_gradient_monotonic", "?")
    readme = "\n\n".join([
        _summary_table(r),
        f"Severity gradient — score falls from mild to moderate to egregious in **{grad}** flaw/recording "
        f"combinations. {_clean_pairs(r)}",
    ])
    report = "\n\n".join([
        "#### 6.1 Summary",
        _summary_table(r),
        "#### 6.2 Real orators (texts 9-11, held out) — target IoU (false-positive seconds) per tier",
        _tier_table(r, "heldout_orators") if "heldout_orators" in r else "",
        "#### 6.2b Held-out TTS texts — target IoU (false-positive seconds) per tier",
        _tier_table(r, "heldout_tts"),
        "#### 6.3 Human recordings, same-speaker reference",
        _tier_table(r, "real_same_speaker"),
        "#### 6.4 Human recordings against the TTS baseline",
        _tier_table(r, "real_cross_speaker"),
        _clean_pairs(r),
        "#### 6.4b Mode B (no reference recording)",
        _tier_table(r, "mode_b") if "mode_b" in r else "",
        f"#### 6.5 Severity gradient\nScore falls monotonically mild → moderate → egregious in {grad} cases.",
        "#### 6.6 Calibrated parameters\n"
        f"Clarity measure `{cal.get('clarity_feature')}`; floors `{cal.get('floors')}`; "
        f"k (different recording) `{g.get('k_noise')}`; k (edited copy) `{g.get('k_same_recording', 3.0)}`; "
        f"same-recording gate (timbre distance) `{g.get('same_recording_max_dist')}`.",
    ])
    return readme, report


def _replace(path: Path, block: str) -> None:
    text = path.read_text(encoding="utf-8")
    new = f"<!-- RESULTS:BEGIN (generated by scripts/render_results.py) -->\n{block}\n<!-- RESULTS:END -->"
    if "<!-- RESULTS:BEGIN" in text:
        text = re.sub(r"<!-- RESULTS:BEGIN.*?<!-- RESULTS:END -->", lambda _: new, text, flags=re.S)
    else:
        text = re.sub(r"<!-- RESULTS(_TABLE)? -->", lambda _: new, text, count=1)
    path.write_text(text, encoding="utf-8")


def main() -> None:
    readme, report = render()
    _replace(ROOT / "README.md", readme)
    _replace(ROOT / "technical_report.md", report)
    print("README.md and technical_report.md updated from", RESULTS.relative_to(ROOT))


if __name__ == "__main__":
    main()
